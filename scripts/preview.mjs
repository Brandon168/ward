#!/usr/bin/env node
// Builds preview/ward-popup.html: the real popup (popup.html/css/js and its modules) with sample data, packed into one
// self-contained file for Paseo's Files panel > Preview, which allows only inline scripts and blob: modules.
// Usage: node scripts/preview.mjs   (rerun after each UI change; then reopen or refresh the preview)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, f), 'utf8');
// Dependency order: each module's imports are created first, so their blob URLs exist when it is rewritten.
const MODULES = ['vendor/public_suffix_list.js', 'bw.js', 'coord.js', 'autofill.js', 'touch.js', 'sync.js', 'popup.js'];
// The popup refuses to run framed (window !== top), and Paseo's preview is a frame: in this sample-data copy only,
// shadow `top` so the popup takes itself for the top window. The extension itself is unchanged.
const mods = MODULES.map((f) => [f, f === 'popup.js' ? `const top = window; // preview only\n${read(f)}` : read(f)]);
for (const [f, src] of mods) {
  for (const [, dep] of src.matchAll(/from '\.\/([\w/.-]+)'/g)) {
    if (MODULES.indexOf(dep) < 0 || MODULES.indexOf(dep) > MODULES.indexOf(f)) throw new Error(`${f} imports ${dep}: update MODULES`);
  }
}
const inline = (s) => s.replace(/<\/(script|style)/gi, '<\\/$1'); // keep embedded text from closing its tag
const json = JSON.stringify(mods).replace(/</g, '\\u003c');
const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<title>Ward popup preview</title>
<!-- Generated by scripts/preview.mjs from the working tree. Sample data only. -->
<style>${inline(read('popup.css'))}</style>
<style>html { min-height: 100%; } body { margin: 12px auto !important; box-shadow: 0 0 0 1px var(--line), 0 8px 30px #0006; border-radius: 10px; }</style>
<script>${inline(read('theme.js'))}</script>
<script>${inline(read('scripts/preview-shim.js'))}</script>
<script type="application/json" id="ward-modules">${json}</script>
<script>
  const urls = {};
  for (const [name, src] of JSON.parse(document.getElementById('ward-modules').textContent)) {
    const code = src.replace(/from '\\.\\/([\\w/.-]+)'/g, (_, dep) => \`from '\${urls[dep]}'\`);
    urls[name] = URL.createObjectURL(new Blob([code], { type: 'text/javascript' }));
  }
  import(urls['popup.js']).catch((e) => (document.body.textContent = 'Preview failed: ' + e));
</script>
</head>
<body><main id="app"></main></body>
</html>
`;
const out = join(root, 'preview', 'ward-popup.html');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, html);
console.log(`wrote preview/ward-popup.html (${Math.round(html.length / 1024)} KB)`);
