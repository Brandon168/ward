#!/usr/bin/env node
// Builds preview/ward-popup.html (the real popup: popup.html/css/js and its modules, with sample data), one file for
// each extension-owned window (passkey and save offers, see VIEWS) and preview/ward-inpage.html (the in-page login
// menu and save bar). Each is one self-contained file that works in a sandboxed HTML preview panel, which allows only
// inline scripts and blob: modules.
// Usage: node scripts/preview.mjs   (rerun after each UI change; then reopen or refresh the preview)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(root, f), 'utf8');
// Dependency order: each module's imports are created first, so their blob URLs exist when it is rewritten.
const MODULES = ['vendor/public_suffix_list.js', 'bw.js', 'coord.js', 'autofill.js', 'touch.js', 'sync.js', 'vendor/eff_large_wordlist.js', 'gen.js', 'popup.js'];
// The popup refuses to run framed (window !== top), and a preview panel is a frame: in these sample-data copies only,
// shadow `top` so the popup takes itself for the top window, and `location` so a copy opens as one of the windows
// background.js opens (#pk=, #save=). The extension itself is unchanged.
const prelude = (hash) => `const top = window; // preview only\n${hash ? `const location = { hash: '${hash}', reload() {} }; // preview only\n` : ''}`;
const modsFor = (hash) => MODULES.map((f) => [f, f === 'popup.js' ? prelude(hash) + read(f) : read(f)]);
for (const [f, src] of modsFor('')) {
  for (const [, dep] of src.matchAll(/from '\.\/([\w/.-]+)'/g)) {
    if (MODULES.indexOf(dep) < 0 || MODULES.indexOf(dep) > MODULES.indexOf(f)) throw new Error(`${f} imports ${dep}: update MODULES`);
  }
}
const inline = (s) => s.replace(/<\/(script|style)/gi, '<\\/$1'); // keep embedded text from closing its tag
// Every window a user can see has a preview file, so none of them drifts from the design system unnoticed.
// [file, title, sample hand-off in preview-shim.js, hash background.js would open]
const VIEWS = [
  ['ward-popup.html', 'Ward popup', 'popup', ''],
  ['ward-passkey.html', 'Ward: sign in with passkey', 'passkey', '#pk=demo'],
  ['ward-passkey-save.html', 'Ward: save passkey', 'passkey-save', '#pk=demo'],
  ['ward-save.html', 'Ward: save login', 'save', '#save=demo'],
  ['ward-save-update.html', 'Ward: update password', 'save-update', '#save=demo'],
  ['ward-save-card.html', 'Ward: save card', 'save-card', '#save=demo'],
  ['ward-twostep.html', 'Ward: two-step login', 'twostep', ''],
  ['ward-item.html', 'Ward: item details', 'item', ''], // the popup, opened on GitHub's details
  ['ward-item-window.html', 'Ward: item details in a window', 'item-window', '#item=demo'], // its New window button
];
mkdirSync(join(root, 'preview'), { recursive: true });
for (const [file, name, view, hash] of VIEWS) {
  const json = JSON.stringify(modsFor(hash)).replace(/</g, '\\u003c');
  const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<title>${name} preview</title>
<!-- Generated by scripts/preview.mjs from the working tree. Sample data only. -->
<style>${inline(read('popup.css'))}</style>
<style>html { min-height: 100%; } body { margin: 12px auto !important; box-shadow: 0 0 0 1px var(--line), 0 8px 30px #0006; border-radius: 10px; } body.window { width: 410px; }</style>
<script>${inline(read('theme.js'))}</script>
<script>window.WARD_VIEW = '${view}';</script>
<script>${inline(read('scripts/preview-shim.js'))}</script>
<script type="application/json" id="ward-modules">${json}</script>
<script>
  const urls = {};
  for (const [name, src] of JSON.parse(document.getElementById('ward-modules').textContent)) {
    const code = src.replace(/from '\\.\\/([\\w/.-]+)'/g, (_, dep) => \`from '\${urls[dep]}'\`);
    urls[name] = URL.createObjectURL(new Blob([code], { type: 'text/javascript' }));
  }
  import(urls['popup.js']).catch((e) => (document.body.textContent = 'Preview failed: ' + e));
  import(urls['bw.js']).then((bw) => window.wardPreviewSeed(bw)); // the same module instance the popup uses
</script>
</head>
<body><main id="app"></main></body>
</html>
`;
  writeFileSync(join(root, 'preview', file), html);
  console.log(`wrote preview/${file} (${Math.round(html.length / 1024)} KB)`);
}

// preview/ward-inpage.html: a sample sign-in page running the real inpage.js (the menu under login fields and the
// save bar), with a fake chrome.runtime. Click the username or password field to open the menu.
// preview/ward-inpage-passkey.html: the same page asking for passkey autofill, which Ward holds (bridge.js would set
// wardHeld), so the menu lists the site's passkey first and ends with "Use device or security key".
// preview/ward-inpage-locked.html: the same page while Ward is locked: one "Ward is locked" row that opens Ward.
const inpagePage = (passkey, locked) => `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<title>Ward in-page preview</title>
<!-- Generated by scripts/preview.mjs from the working tree. Sample data only. -->
<style>
  body { margin: 0; min-height: 100vh; font: 15px/1.4 Georgia, serif; background: #f3f1ec; color: #222; }
  form { width: 300px; margin: 90px auto 0; padding: 24px; background: #fff; border: 1px solid #ddd; }
  label { display: block; margin: 12px 0 4px; color: #a3174b; } input { width: 100%; box-sizing: border-box; padding: 8px; font: inherit; }
  button { width: 100%; margin-top: 16px; padding: 10px; border: 0; background: #0062ff; color: #fff; font: inherit; }
  @media (prefers-color-scheme: dark) { body { background: #1c1c1c; color: #ddd; } form { background: #262626; border-color: #333; } }
</style>
<script>
  const logins = [
    { k: 'v:1', name: 'Example Bank', username: 'ann.lee', password: 'pw1' },
    { k: 'v:2', name: 'examplebank.com', username: 'annlee84', password: 'pw2' },
    { k: 'v:3', name: 'Example Bank (business)', username: 'ann@example.com', password: 'pw3' },
  ];
  const listeners = [];${passkey ? `
  window.wardHeld = 'preview';
  logins.splice(0, 1, { k: 'v:1:0', pk: true, name: 'Example Bank', username: 'ann.lee' }); // its login isn't listed twice
  logins.push({ k: 'device', device: true });` : ''}${locked ? `
  logins.splice(0, logins.length, { k: 'locked', locked: true }); // Ward is locked: one row that opens Ward` : ''}
  window.chrome = { runtime: {
    id: 'preview', // inpage.js asks only while the extension is alive (chrome.runtime.id)
    sendMessage: async (m) => m.bwliteMenu ? logins.map(({ password, ...l }) => l)
      : m.bwliteFillKey ? logins.find((l) => l.k === m.bwliteFillKey) : null,
    onMessage: { addListener: (f) => listeners.push(f) },
  } };
  Object.defineProperty(navigator, 'clipboard', { value: { writeText: async () => {} } });
  addEventListener('load', () => listeners.forEach((f) => f({ bwliteBar: '00000000-0000-0000-0000-000000000000', what: 'login' })));
</script>
<script>${inline(read('inpage.js'))}</script>
</head>
<body>
<form onsubmit="return false"><label>Username<input name="username" autocomplete="username${passkey ? ' webauthn' : ''}"></label>
<label>Password<input type="password" name="password"></label><button>Sign in</button></form>
</body>
</html>
`;
const page = inpagePage(false);
writeFileSync(join(root, 'preview', 'ward-inpage.html'), page);
writeFileSync(join(root, 'preview', 'ward-inpage-passkey.html'), inpagePage(true));
writeFileSync(join(root, 'preview', 'ward-inpage-locked.html'), inpagePage(false, true));

// preview/ward-twostep-key.html: the small window Ward opens on the vault server for a security key (twostep.js runs
// there with the browser's own prompt on top). Here the prompt never answers.
const keyPage = `<!doctype html>
<html><head><meta charset="utf-8"><title>Ward two-step key window preview</title>
<!-- Generated by scripts/preview.mjs from the working tree. -->
<script>
  Object.defineProperty(navigator, 'credentials', { value: { get: () => new Promise(() => {}) } });
  addEventListener('load', () => (${inline(read('twostep.js')).replace(/^[\s\S]*?export async function securityKeyPrompt/m, 'async function securityKeyPrompt')
    .replace(/\n}\s*$/, '\n}')})({ challenge: 'AA' }, 'bw.example'));
</script></head><body>{"status":"ok"}</body></html>
`;
writeFileSync(join(root, 'preview', 'ward-twostep-key.html'), keyPage);
console.log('wrote preview/ward-twostep-key.html');
console.log(`wrote preview/ward-inpage.html (${Math.round(page.length / 1024)} KB)`);
console.log('wrote preview/ward-inpage-passkey.html');
console.log('wrote preview/ward-inpage-locked.html');
